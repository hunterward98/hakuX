#!/usr/bin/env python3
"""Halo 2 (4D530064.3): the frame limiter's vblank spin made a sleep.

The limiter (0x12B0E0) waits for the vblank count its ISR bumps (64-bit at 0x485AB0) in a tight
loop at 0x12B330..0x12B343. On the RG405M that spin was ~60% of the vCPU's samples in the Cairo
Station intro: to the host scheduler a thread always 100% busy, time-sliced against the render,
push-buffer and audio threads even while it only waits. Here the loop body jumps to a cave that
checks the count and, short of it, calls KeDelayExecutionThread(KernelMode, FALSE, -0.5 ms) before
checking again: the vCPU idles (interrupts still arrive and bump the count) instead of spinning.

The cave is in the header page over the logo bitmap at 0x10CC0, where the 60/120 fps mods put
theirs: use one or the other.
Usage: h2_idle_limiter.py <Halo 2 iso> > mods/4D530064.3/idlelimiter/mod.txt
Needs keystone-engine.
"""
import struct, sys
from keystone import Ks, KS_ARCH_X86, KS_MODE_32

LOOP, LOOP_END, CAVE = 0x12B330, 0x12B344, 0x10CC0
COUNT, THUNK_KE_DELAY = 0x485AB0, 0x41165C          # KeDelayExecutionThread = ordinal 99
INTERVAL = CAVE + 0x40                               # LARGE_INTEGER, relative 100 ns units
HALF_MS = -5000


def xbe_bytes(iso):
    with open(iso, 'rb') as f:
        base = 0
        for b in (0, 0x18300000, 0xFD90000, 0x2080000):
            f.seek(b + 0x10000)
            if f.read(20) == b'MICROSOFT*XBOX*MEDIA':
                base = b
                break
        f.seek(base + 0x10000)
        hdr = f.read(0x800)
        root_sec, root_size = struct.unpack_from('<II', hdr, 20)
        f.seek(base + root_sec * 2048)
        d = f.read(root_size)

        def walk(off, name='default.xbe'):
            l, r, sec, size, attr, nl = struct.unpack_from('<HHIIBB', d, off * 4)
            n = d[off * 4 + 14: off * 4 + 14 + nl].decode('latin1').lower()
            if n == name:
                return sec, size
            nxt = l if n > name else r
            return walk(nxt) if nxt else None
        sec, size = walk(0)
        f.seek(base + sec * 2048)
        return f.read(size)


def va_bytes(xbe, va, n):
    bva, = struct.unpack_from('<I', xbe, 0x104)
    if va < bva + struct.unpack_from('<I', xbe, 0x10C)[0]:       # in the headers
        return xbe[va - bva: va - bva + n]
    nsec, sh = struct.unpack_from('<II', xbe, 0x11C)
    for i in range(nsec):
        _, sva, vsz, raw, rsz = struct.unpack_from('<IIIII', xbe, sh - bva + i * 56)
        if sva <= va < sva + vsz:
            return xbe[raw + va - sva: raw + va - sva + n]
    raise SystemExit(f'{va:08x}: not in the XBE')


def asm(src, addr):
    enc, _ = Ks(KS_ARCH_X86, KS_MODE_32).asm(src, addr)
    return bytes(enc)


def main():
    xbe = xbe_bytes(sys.argv[1])
    cave = asm(f"""
    chk:
        mov edx, dword ptr [{COUNT:#x}]
        cmp dword ptr [{COUNT + 4:#x}], eax
        jl wait
        jg done
        cmp edx, ecx
        jae done
    wait:
        push eax
        push ecx
        push {INTERVAL:#x}
        push 0
        push 0
        call dword ptr [{THUNK_KE_DELAY:#x}]
        pop ecx
        pop eax
        jmp chk
    done:
        jmp {LOOP_END:#x}
    """, CAVE)
    assert len(cave) <= 0x40, len(cave)
    data = struct.pack('<q', HALF_MS)
    hook = asm(f"jmp {CAVE:#x}", LOOP)
    hook += b'\x90' * (LOOP_END - LOOP - len(hook))
    old_loop = va_bytes(xbe, LOOP, len(hook))
    assert old_loop[:2] == b'\x8b\x15', old_loop.hex()           # mov edx, [0x485ab0]
    hx = lambda b: ' '.join(f'{x:02X}' for x in b)
    print("name: Idle frame limiter")
    print("description: The frame limiter sleeps while it waits for the vblank instead of spinning, so the "
          "emulated CPU gives its core to the GPU and audio threads. Not with the 60/120 fps mods.")
    print("author: hunterward98 (generated by tools/mods/h2_idle_limiter.py)")
    print()
    print("[default.xbe]")
    print(f"0x{LOOP:08X}: {hx(old_loop)} -> {hx(hook)}")
    for off in range(0, len(cave), 32):
        chunk = cave[off:off + 32]
        print(f"0x{CAVE + off:08X}: {hx(va_bytes(xbe, CAVE + off, len(chunk)))} -> {hx(chunk)}")
    print(f"0x{INTERVAL:08X}: {hx(va_bytes(xbe, INTERVAL, 8))} -> {hx(data)}")


main()
